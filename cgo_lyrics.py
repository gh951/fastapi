# ── 열린 줄은 막는 게 아니라 '끌고 가는 줄'로 쓴다 ──
# 뒤척이다가네 ✗  —  종결어미를 붙이면 말이 안 된다
# 뒤척이다가도 ✓  —  양보로 받으면 감정의 폭이 오히려 넓어진다
#   밤새 뒤척이다가도 / 아침이면 웃어
# 열린 줄은 절의 마지막에 놓지 않는다. 반드시 다음 줄이 닫아준다.
OPEN_FORMS = [
 ('다가', {'양보': '다가도', '화제': '다가는'}),
 ('면서', {'양보': '면서도'}),
 ('려고', {'중단': '려다'}),
 ('지만', {'강조': '지만도'}),
]

def openforms(line):
    """열린 줄이 취할 수 있는 꼴 — 전부 '아직 안 끝난' 말투다"""
    if not _is_open(line):
        return {}
    d = {'기본': line}
    for tail, subs in OPEN_FORMS:
        if line.endswith(tail):
            stem = line[: -len(tail)]
            for m, new in subs.items():
                d[m] = stem + new
            break
    return d

def variants(line):
    if _is_open(line):
        return {}
    """한 줄 → {말투: 바뀐 줄}. 못 바꾸면 비어 있다."""
    if line.endswith(_NOVARY):
        return {}
    out = {}
    for tail, subs in RULES:
        if line.endswith(tail):
            if tail == '거야':
                return _geoya(line)
            if tail == '가' and not _ok가(line):
                continue
            if tail == '이야' and not _ok이야(line):
                continue
            stem = line[: -len(tail)]
            if tail in _ATTACH:
                stem = stem.rstrip()          # 앞 띄어쓰기를 지운다
            for m, new in subs.items():
                out[m] = stem + new
            # 걷다(걸어)만 따로 — ㄹ 탈락이 아니라 ㄷ 불규칙이다
            w = line.split()[-1] if line.split() else ''
            if w in _걷:
                if '영탄' in out:
                    out['영탄'] = ' '.join(line.split()[:-1] + [_걷[w]])
            else:
                if '영탄' in out:
                    out['영탄'] = _rdrop(out['영탄'])
                if '의문' in out:
                    out['의문'] = _lkka(_ulkka(out['의문']))
            break
    return out

# ── 우리말 불규칙 ① ㄹ 탈락 ──
# ㄴ 앞에서 ㄹ은 반드시 떨어진다.
#   알다 → 아네 (알네 ✗)   울다 → 우네 (울네 ✗)   살다 → 사네 (살네 ✗)
#   만들다 → 만드네         기울다 → 기우네        말다 → 마네
# 'ㄹ까'(알까)는 그대로다 — ㄹ 탈락은 ㄴ·ㅅ·ㅂ 앞에서만 일어난다.
