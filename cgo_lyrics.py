# ══ 1. 한글 자모 ══
CHO = list('ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ')
JUNG = list('ㅏㅐㅑㅒㅓㅔㅕㅖㅗㅘㅙㅚㅛㅜㅝㅞㅟㅠㅡㅢㅣ')
JONG = [''] + list('ㄱㄲㄳㄴㄵㄶㄷㄹㄺㄻㄼㄽㄾㄿㅀㅁㅂㅄㅅㅆㅇㅈㅊㅋㅌㅍㅎ')
BASE = 0xAC00

def split(ch):
    """'슬' → ('ㅅ','ㅡ','ㄹ')"""
    c = ord(ch) - BASE
    if c < 0 or c > 11171:
        return (ch, '', '')
    return (CHO[c // 588], JUNG[(c % 588) // 28], JONG[c % 28])

def join(cho, jung, jong=''):
    """('ㅅ','ㅡ','ㄹ') → '슬'"""
    return chr(BASE + CHO.index(cho)*588 + JUNG.index(jung)*28 + JONG.index(jong))

def head(word):   return split(word[0])[0]          # 첫 자음 (두운)
def vowel(word):  return split(word[0])[1]          # 첫 모음 (모운)
def tail(word):   return split(word[-1])[1:]        # 끝 모음+받침 (각운)

