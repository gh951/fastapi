# ── 우리말 불규칙 ② ㄹ 어간 ──
# '갈 거야 → 가리라' 는 맞다. 갈 = 가다 + 관형형 ㄹ 이니 ㄹ을 뗀다.
# 그런데 '말 거야 → 마리라' 는 틀렸다. 말다의 ㄹ은 어간이라 남아야 한다.
#   해내고 말 거야 → 해내고 말리라 (마리라 ✗)
#   전부를 걸 거야 → 전부를 걸리라 (거리라 ✗)
_ㄹ어간 = {'말','걸','살','알','울','들','열','밀','풀','길','달','멀','졸','얼',
           '흔들','만들','기울','떠들','내밀','매달','베풀','저물'}

def _geoya(line):
    """'~ㄹ 거야' 꼴은 ㄹ(관형형)을 떼고 어미를 붙여야 말이 된다.
       버텨낼 거야 → 버텨내리라 (버텨낼리라 ✗)
       지지 않을 거야 → 지지 않으리라 (지지 않을리라 ✗)"""
    stem = line[:-2].rstrip()            # '거야' 제거
    if not stem:
        return {}
    c, j, t = split(stem[-1])
    last = stem.split()[-1] if stem.split() else stem
    if t == 'ㄹ' and last in _ㄹ어간:       # ㄹ이 어간이다 — 떼면 안 된다
        return {'의지': stem + '리라', '영탄': stem + '겠지', '의문': stem + '까'}
    if t == 'ㄹ':                         # 관형형 ㄹ 이 붙어 있다
        bare = stem[:-1] + join(c, j)     # ㄹ 떼기
        # 받침 없는 어간이면 '리라', 'ㅡ'로 끝나면 '으리라'
        c2, j2, t2 = split(bare[-1])
        link = '으' if t2 else ''
        # 의지는 '으'를 살리고(않으리라) 영탄은 떼야 한다(않겠지).
        #   굽히지 않을 거야 → 않으리라 ✓ / 않겠지 ✓ (않으겠지 ✗)
        #   버텨낼 거야      → 버텨내리라 ✓ / 버텨내겠지 ✓
        겠 = (stem[:-1] if join(c, j) == '으' and stem[:-1] else bare) + '겠지'
        return {'의지': bare + link + '리라',
                '영탄': 겠,
                '의문': stem + '까'}       # 버텨낼까
    return {'의지': stem + '리라', '영탄': stem + '겠지', '의문': stem + '걸까'}

