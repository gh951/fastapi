# ══ 6. 거꾸로 색인 — 초성을 첫 글자에만 걸지 않는다 ══
# 된소리는 같은 집안 — ㄱ칸에 '깊은'도 들어간다
_FAM = {'ㄲ': 'ㄱ', 'ㄸ': 'ㄷ', 'ㅃ': 'ㅂ', 'ㅆ': 'ㅅ', 'ㅉ': 'ㅈ'}

# 우리말에 첫소리로 오기 어려운 소리 — 머리 등급을 쓰지 않는다
약한머리 = {'ㄹ', 'ㅋ', 'ㅌ', 'ㅍ'}

# 우리말에 실제로 흔한 정도 — 추첨통에 넣는 표 수.
# ㅋㅌㅍ 로 두운을 맞추는 것은 우리말에 없는 기법이라 거의 뽑지 않는다.
무게 = {'ㄱ': 9, 'ㄴ': 8, 'ㄷ': 7, 'ㄹ': 7, 'ㅁ': 8, 'ㅂ': 7, 'ㅅ': 9,
        'ㅇ': 9, 'ㅈ': 7, 'ㅎ': 7, 'ㅊ': 4, 'ㅋ': 1, 'ㅌ': 1, 'ㅍ': 1}

머리, 어절, 글자 = 3, 2, 1


def fam(c):
    return _FAM.get(c, c)


def marks(line):
    """줄 하나 → {초성: (등급, 몇 번 나오는지)}

       '그 자리에 주저앉아' →
            ㄱ (머리, 1)  ㅈ (어절, 3)  ㄹ (글자, 1)  ㅇ (글자, 3) …
    """
    ws = [w for w in line.split() if w and '가' <= w[0] <= '힣']
    if not ws:
        return {}
    out = {}
    def put(c, grade):
        g, n = out.get(c, (0, 0))
        out[c] = (max(g, grade), n)
    # 글자 단위 — 몇 번 나오는지까지 센다
    cnt = {}
    for ch in line:
        if '가' <= ch <= '힣':
            c = fam(split(ch)[0])
            cnt[c] = cnt.get(c, 0) + 1
    for c, n in cnt.items():
        out[c] = (글자, n)
    # 어절 첫소리
    for w in ws:
        c = fam(head(w))
        out[c] = (max(out.get(c, (0, 0))[0], 어절), cnt.get(c, 1))
    # 줄의 첫 글자 — 가장 세다
    c0 = fam(head(ws[0]))
    out[c0] = (머리, cnt.get(c0, 1))
    return out


def build(bank):
    """감정 창고 하나 → {초성: {등급: [줄…]}}

       한 줄이 여러 칸에 들어간다. '그 자리에 주저앉아' 는
       ㄱ칸(머리)·ㅈ칸(어절)·ㄹ칸(글자) 에 모두 들어간다.
    """
    lines = []
    for v in bank.values():
        lines.extend(v)
    lines = list(dict.fromkeys(lines))
    idx = {}
    for l in lines:
        for c, (g, n) in marks(l).items():
            # ㄹㅋㅌㅍ 는 등급을 아예 두지 않고 한 통에 담는다.
            # 등급을 두면 '레코드 옆의 교복' 같은 외래어 줄이 늘 먼저 뽑혀 버린다.
            # 한 통에 담으면 '서랍 속 연필'(랍) 과 똑같은 자격으로 경쟁한다.
            if c in 약한머리:
                g = 글자
            # 글자 등급은 그 소리가 두 번 이상 나와야 '들린다'.
            # 다만 ㄹㅋㅌㅍ 는 한 번이 최선이다 — 우리말에 드문 소리라 더 바랄 수 없다.
            if g == 글자 and n < (1 if c in 약한머리 else 2):
                continue
            idx.setdefault(c, {}).setdefault(g, []).append(l)
    return idx


def draw(idx, c, rng, used, prefer=None, 맺기=False, obj=None, 여백=False):
    """초성 c 칸에서 한 줄 뽑는다 — 센 등급부터, 쓴 줄은 건너뛴다.
       맺기=True 면 '뒤에 뭐가 와야 끝나는 줄'(~처럼·~로·~위에)은 빼고 뽑는다.
       여백=True 면 거꾸로 그런 줄을 '골라' 뽑는다 — 다음 절로 넘겨주는 자리에 쓴다."""
    order = prefer or ((어절, 글자) if c in 약한머리 else (머리, 어절, 글자))
    for g in order:
        cand = [l for l in idx.get(c, {}).get(g, []) if l not in used]
        if 여백:
            뜸 = [l for l in cand
                  if _needs_next(l if obj is None else l.replace('□', obj))]
            if 뜸:
                cand = 뜸
        if 맺기:
            tried = [l for l in cand
                     if not _needs_next(l if obj is None else l.replace('□', obj))]
            if tried:
                cand = tried
        if cand:
            l = rng.choice(cand)
            used.add(l)
            return l, g
    return None, 0


def chosung_lottery(rng, n, pool=None):
    """초성 추첨 — 우리말에 흔한 소리가 더 잘 나오게 표 수를 다르게 준다"""
    pool = [c for c in (pool or 무게) if 무게.get(c, 0) > 0]
    out = []
    while len(out) < n and pool:
        tickets = []
        for c in pool:
            tickets += [c] * 무게.get(c, 1)
        c = rng.choice(tickets)
        out.append(c)
        pool = [x for x in pool if x != c]
    return out

